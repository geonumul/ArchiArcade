/// 학과 이름은 lib/majors.ts 의 ko/en 만 있으므로, 그 밖의 언어는 영어로 떨어뜨린다.
export function majorFor(code: string, lang: SchoolLang, majors: readonly { code: string; ko: string; en: string }[]): string {
  const m = majors.find((x) => x.code === code);
  if (!m) return code;
  return lang === "ko" ? m.ko : m.en;
}
